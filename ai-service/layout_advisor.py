MM_TO_INCHES = 0.001 / 0.0254     # Exact international inch: 1 in = 25.4 mm (~0.03937008 in/mm)


def _resolve_dimension(
    container: Dict[str, Any],
    dim_name: str,
    alias_specs: List[Tuple[str, float, Optional[float], Optional[float], str]],
    is_required: bool = True,
    default_inches: Optional[float] = None
) -> Tuple[bool, Optional[str], Optional[float], List[str]]:
    """
    Safely resolves a spatial dimension from a container dictionary across multiple aliases.
    alias_specs: list of tuples: (alias_name, scale_to_inches, min_val_native, max_val_native, unit_category)
      where unit_category is 'imperial' or 'metric'.

    Returns:
    - (is_ok, error_message, resolved_inches, list_of_matched_alias_names)
    """
    candidates = []
    for alias_name, scale_factor, min_native, max_native, unit_cat in alias_specs:
        if alias_name in container:
            ok, err, raw_val = _parse_finite_float(
                container[alias_name], alias_name, min_val=min_native, max_val=max_native
            )
            if not ok:
                return False, err, None, []
            val_in = raw_val * scale_factor
            if not math.isfinite(val_in):
                return False, f"'{alias_name}' converted value is non-finite.", None, []
            candidates.append((alias_name, val_in, raw_val, unit_cat))

    if len(candidates) == 0:
        if is_required:
            alias_list = ", ".join(f"'{s[0]}'" for s in alias_specs)
            return False, f"Plot {dim_name} must be specified via one of: {alias_list}.", None, []
        return True, None, default_inches, []

    if len(candidates) > 1:
        for i in range(len(candidates)):
            for j in range(i + 1, len(candidates)):
                name_i, val_i, raw_i, _ = candidates[i]
                name_j, val_j, raw_j, _ = candidates[j]
                diff = abs(val_i - val_j)
                if diff > DIMENSION_TOLERANCE_INCHES:
                    return False, (
                        f"Conflicting dimension aliases provided for {dim_name}: "
                        f"'{name_i}' ({raw_i} -> {val_i:.2f}\") and '{name_j}' ({raw_j} -> {val_j:.2f}\") "
                        f"differ by {diff:.2f}\", exceeding allowable tolerance of {DIMENSION_TOLERANCE_INCHES}\"."
                    ), None, []

    # All candidates agree within tolerance; use consistent canonical inches
    resolved_in = sum(c[1] for c in candidates) / len(candidates)
    matched_names = [c[0] for c in candidates]
    return True, None, resolved_in, matched_names



def _parse_finite_float(
    val: Any,
    field_name: str,
    min_val: Optional[float] = None,
    max_val: Optional[float] = None
) -> Tuple[bool, Optional[str], float]:
    """
    Safely parses a finite floating-point value.
    Rejects booleans, non-numeric types, NaN, +Inf, -Inf, and values outside bounds.
    """
    if val is None:
        return False, f"Missing required numeric field '{field_name}'.", 0.0

    # In Python, isinstance(True, int) is True; explicitly reject booleans
    if isinstance(val, bool):
        return False, f"'{field_name}' must be numeric, not boolean.", 0.0

    try:
        num = float(val)
    except (ValueError, TypeError):
        return False, f"'{field_name}' must be numeric (received {type(val).__name__}).", 0.0

    if not math.isfinite(num):
        return False, f"'{field_name}' must be a finite numeric value (received {val}).", 0.0

    if min_val is not None and num < min_val:
        return False, f"'{field_name}' ({num}) is below minimum allowed value ({min_val}).", 0.0

    if max_val is not None and num > max_val:
        return False, f"'{field_name}' ({num}) exceeds maximum allowed architectural boundary ({max_val}).", 0.0

    return True, None, num


class LayoutFeasibilityAdvisor:
    """
    Offline Layout Feasibility Advisor with strict finite-input validation
    and non-destructive architectural guidance.
    """
    def __init__(self, checkpoint_path: Optional[str] = None, backend: Optional[str] = None):
        self.checkpoint_path = checkpoint_path
        self.backend = backend  # "pytorch", "numpy", or None (auto-detect)
        self.model: Optional[Any] = None
        self.is_model_ready = False
        self.init_error: Optional[str] = None
        self.metadata: Dict[str, Any] = {}

        self._load_checkpoint()

    def _load_checkpoint(self):
        """Safely loads and verifies the trained model via PyTorch or NumPy adapter."""
        target_path = self.checkpoint_path
        target_backend = self.backend

        if target_backend is not None:
            target_backend = target_backend.lower().strip()
            if target_backend not in ("pytorch", "numpy"):
                self.init_error = f"Unsupported backend '{target_backend}'. Must be 'pytorch' or 'numpy'."
                self.is_model_ready = False
                return

        if target_path is None:
            if target_backend == "numpy":
                target_path = DEFAULT_NUMPY_CHECKPOINT_PATH
            elif target_backend == "pytorch":
                target_path = DEFAULT_CHECKPOINT_PATH
            else:
                # Auto-detect: if PyTorch is absent, prefer NumPy .npz
                if not HAS_TORCH or torch is None:
                    target_path = DEFAULT_NUMPY_CHECKPOINT_PATH
                elif os.path.exists(DEFAULT_CHECKPOINT_PATH):
                    target_path = DEFAULT_CHECKPOINT_PATH
                elif os.path.exists(DEFAULT_NUMPY_CHECKPOINT_PATH):
                    target_path = DEFAULT_NUMPY_CHECKPOINT_PATH
                else:
                    target_path = DEFAULT_CHECKPOINT_PATH

        self.checkpoint_path = target_path

        if not os.path.exists(self.checkpoint_path):
            self.init_error = f"Checkpoint file not found: {self.checkpoint_path}"
            self.is_model_ready = False
            return

        is_npz = self.checkpoint_path.endswith(".npz") or target_backend == "numpy"

        if is_npz:
            self._load_numpy_checkpoint()
        else:
            if not HAS_TORCH or torch is None:
                # Automatic fallback to .npz if available
                if os.path.exists(DEFAULT_NUMPY_CHECKPOINT_PATH):
                    self.checkpoint_path = DEFAULT_NUMPY_CHECKPOINT_PATH
                    self._load_numpy_checkpoint()
                    return
                self.init_error = "PyTorch is not installed and no NumPy checkpoint was found."
                self.is_model_ready = False
                return
            self._load_pytorch_checkpoint()

    def _load_numpy_checkpoint(self):
        try:
            weights_data = np.load(self.checkpoint_path, allow_pickle=False)
            weights_dict = {f: weights_data[f] for f in weights_data.files}
            self.model = NumpySpatialLayoutMLP(weights_dict)
            self.metadata = {
                "version": "1.0.0",
                "stage": "8E-F",
                "architecture": "NumpySpatialLayoutMLP",
                "backend": "NumPy",
                "total_parameters": self.model.count_parameters(),
                "best_val_loss": None,
                "device": "CPU"
            }
            self.is_model_ready = True
        except Exception as e:
            self.init_error = f"Failed to initialize NumPy advisor model: {str(e)}"
            self.is_model_ready = False
            self.model = None

    def _load_pytorch_checkpoint(self):
        try:
            ckpt = torch.load(self.checkpoint_path, map_location="cpu")
            in_features = ckpt.get("in_features", IN_FEATURES_DIM)
            num_slots = ckpt.get("num_slots", NUM_ROOM_SLOTS)

            if in_features != IN_FEATURES_DIM:
                raise ValueError(f"Feature dimension mismatch: expected {IN_FEATURES_DIM}, got {in_features}")

            self.model = SpatialLayoutMLP(in_features=in_features, num_slots=num_slots)
            self.model.load_state_dict(ckpt["model_state_dict"])
            self.model.eval()

            self.metadata = {
                "version": ckpt.get("version", "1.0.0"),
                "stage": ckpt.get("stage", "unknown"),
                "architecture": ckpt.get("architecture", "SpatialLayoutMLP"),
                "backend": "PyTorch",
                "total_parameters": ckpt.get("total_parameters", self.model.count_parameters()),
                "best_val_loss": ckpt.get("best_val_loss", None),
                "device": "CPU"
            }
            self.is_model_ready = True
        except Exception as e:
            self.init_error = f"Failed to initialize PyTorch advisor model: {str(e)}"
            self.is_model_ready = False
            self.model = None

    def validate_inputs(self, user_request: Dict[str, Any]) -> Tuple[bool, Optional[str], Dict[str, Any]]:
        """
        Validates input structure and normalizes values with strict finite checks.
        Returns (is_valid, error_message, sanitized_dict).
        """
        if not isinstance(user_request, dict):
            return False, "Input request must be a dictionary.", {}

        plot = user_request.get("plot")
        if not isinstance(plot, dict):
            return False, "Missing or invalid 'plot' configuration.", {}

        # 1. Unit System Validation (Strict)
        raw_unit = plot.get("unitSystem", "imperial")
        if not isinstance(raw_unit, str):
            return False, f"Unit system must be a string, got {type(raw_unit).__name__}.", {}
        unit_system = raw_unit.strip().lower()
        if unit_system not in SUPPORTED_UNITS:
            return False, (
                f"Unsupported unit system '{raw_unit}'. "
                f"Only explicitly supported units are permitted: {sorted(list(SUPPORTED_UNITS))}."
            ), {}

        # 2. Width and Length Resolution with Metric Aliases and Tolerance Checks
        has_explicit_unit_system = "unitSystem" in plot

        width_alias_specs = [
            ("widthInches", 1.0, MIN_SITE_DIM_INCHES, MAX_SITE_DIM_INCHES, "imperial"),
            ("widthFt", 12.0, MIN_SITE_DIM_INCHES / 12.0, MAX_SITE_DIM_INCHES / 12.0, "imperial"),
            ("widthMeters", METERS_TO_INCHES, MIN_SITE_DIM_INCHES * 0.0254, MAX_SITE_DIM_INCHES * 0.0254, "metric"),
            ("widthMm", MM_TO_INCHES, MIN_SITE_DIM_INCHES * 25.4, MAX_SITE_DIM_INCHES * 25.4, "metric"),
        ]
        ok, err, w_in, matched_w = _resolve_dimension(plot, "width", width_alias_specs, is_required=True)
        if not ok:
            return False, err, {}

        length_alias_specs = [
            ("lengthInches", 1.0, MIN_SITE_DIM_INCHES, MAX_SITE_DIM_INCHES, "imperial"),
            ("lengthFt", 12.0, MIN_SITE_DIM_INCHES / 12.0, MAX_SITE_DIM_INCHES / 12.0, "imperial"),
            ("lengthMeters", METERS_TO_INCHES, MIN_SITE_DIM_INCHES * 0.0254, MAX_SITE_DIM_INCHES * 0.0254, "metric"),
            ("lengthMm", MM_TO_INCHES, MIN_SITE_DIM_INCHES * 25.4, MAX_SITE_DIM_INCHES * 25.4, "metric"),
        ]
        ok, err, l_in, matched_l = _resolve_dimension(plot, "length", length_alias_specs, is_required=True)
        if not ok:
            return False, err, {}

        # Validate against contradictory unit declarations and unit-system mismatches
        has_metric_w = any(a in ("widthMeters", "widthMm") for a in matched_w)
        has_imperial_w = any(a in ("widthInches", "widthFt") for a in matched_w)
        has_metric_l = any(a in ("lengthMeters", "lengthMm") for a in matched_l)
        has_imperial_l = any(a in ("lengthInches", "lengthFt") for a in matched_l)

        if has_explicit_unit_system:
            if unit_system == "imperial":
                if (has_metric_w and not has_imperial_w) or (has_metric_l and not has_imperial_l):
                    return False, (
                        "Contradictory unit declaration: 'unitSystem' is explicitly declared as 'imperial', "
                        "but plot dimensions were specified via metric aliases without corresponding imperial values."
                    ), {}
            elif unit_system == "metric":
                if (has_metric_w and not has_metric_l and has_imperial_l) or (has_metric_l and not has_metric_w and has_imperial_w):
                    return False, (
                        "Unit-system mismatch: 'unitSystem' is declared as 'metric', "
                        "but mixed dimension units were provided across width and length."
                    ), {}
        else:
            if (has_metric_w and not has_imperial_w and has_imperial_l and not has_metric_l) or \
               (has_imperial_w and not has_metric_w and has_metric_l and not has_imperial_l):
                return False, (
                    "Unit-system mismatch: plot width and length were provided in conflicting unit systems "
                    "without an explicit unitSystem declaration."
                ), {}
            if has_metric_w or has_metric_l:
                unit_system = "metric"
            else:
                unit_system = "imperial"

        # Verify derived plot area is finite
        plot_area_sqft = (w_in * l_in) / 144.0
        if not math.isfinite(plot_area_sqft) or plot_area_sqft <= 0.0:
            return False, "Derived plot area is non-finite or invalid.", {}

        # 3. Facing Orientation Validation
        raw_facing = plot.get("facing", "East")
        if not isinstance(raw_facing, str):
            return False, f"Facing must be a string, got {type(raw_facing).__name__}.", {}

        # Case-insensitive match against CARDINAL_FACINGS
        facing_matched = None
        for cf in CARDINAL_FACINGS:
            if cf.lower() == raw_facing.strip().lower():
                facing_matched = cf
                break
        if facing_matched is None:
            facing_matched = "East" # Default fallback if unrecognized cardinal string

        # 4. Setback Validation (Configured vs Generic Default)
        setbacks_input = plot.get("setbacks")
        setback_dict = {}
        if setbacks_input is not None:
            if not isinstance(setbacks_input, dict):
                return False, "Optional 'setbacks' must be a dictionary.", {}

            front_specs = [
                ("frontInches", 1.0, 0.0, None, "imperial"),
                ("frontFt", 12.0, 0.0, None, "imperial"),
                ("frontMeters", METERS_TO_INCHES, 0.0, None, "metric"),
                ("frontMm", MM_TO_INCHES, 0.0, None, "metric"),
            ]
            ok, err, front_sb, _ = _resolve_dimension(
                setbacks_input, "front setback", front_specs, is_required=False, default_inches=36.0
            )
            if not ok:
                return False, err, {}

            rear_specs = [
                ("rearInches", 1.0, 0.0, None, "imperial"),
                ("rearFt", 12.0, 0.0, None, "imperial"),
                ("rearMeters", METERS_TO_INCHES, 0.0, None, "metric"),
                ("rearMm", MM_TO_INCHES, 0.0, None, "metric"),
            ]
            ok, err, rear_sb, _ = _resolve_dimension(
                setbacks_input, "rear setback", rear_specs, is_required=False, default_inches=24.0
            )
            if not ok:
                return False, err, {}

            side_specs = [
                ("sideInches", 1.0, 0.0, None, "imperial"),
                ("sideFt", 12.0, 0.0, None, "imperial"),
                ("sideMeters", METERS_TO_INCHES, 0.0, None, "metric"),
                ("sideMm", MM_TO_INCHES, 0.0, None, "metric"),
            ]
            ok, err, side_sb, _ = _resolve_dimension(
                setbacks_input, "side setback", side_specs, is_required=False, default_inches=24.0
            )
            if not ok:
                return False, err, {}
            left_sb = side_sb
            right_sb = side_sb

            # Validate that setbacks do not eliminate the buildable envelope
            if (front_sb + rear_sb) >= l_in:
                return False, f"Sum of front and rear setbacks ({front_sb + rear_sb}\") exceeds total plot length ({l_in}\").", {}
            if (left_sb + right_sb) >= w_in:
                return False, f"Sum of side setbacks ({left_sb + right_sb}\") exceeds total plot width ({w_in}\").", {}

            setback_dict = {
                "front": front_sb,
                "rear": rear_sb,
                "left": left_sb,
                "right": right_sb,
                "source": "CONFIGURED_INPUT"
            }
        else:
            # Generic illustrative setback assumptions
            front_sb = min(36.0, l_in * 0.10)
            rear_sb = min(24.0, l_in * 0.08)
            left_sb = min(24.0, w_in * 0.08)
            right_sb = min(24.0, w_in * 0.08)

            setback_dict = {
                "front": front_sb,
                "rear": rear_sb,
                "left": left_sb,
                "right": right_sb,
                "source": "GENERIC_DEFAULT_ASSUMPTION (Illustrative only; non-jurisdiction specific)"
            }

        # 5. Requirements Validation
        reqs = user_request.get("requirements", {})
        if not isinstance(reqs, dict):
            return False, "'requirements' must be a dictionary.", {}

        # Validate bedrooms
        raw_bhk = reqs.get("bedrooms", 1)
        ok, err, bhk_float = _parse_finite_float(
            raw_bhk, "bedrooms", min_val=1.0, max_val=float(MAX_BEDROOM_COUNT)
        )
        if not ok:
            return False, err, {}

        if not bhk_float.is_integer():
            return False, f"Requested 'bedrooms' must be a whole integer (received {raw_bhk}).", {}

        bhk = int(bhk_float)

        # Validate optional room dimensions if provided
        sanitized_mb = {}
        if "masterBedroom" in reqs and isinstance(reqs["masterBedroom"], dict):
            mb_dict = reqs["masterBedroom"]
            if "width" in mb_dict:
                ok, err, mb_w = _parse_finite_float(mb_dict["width"], "masterBedroom.width", min_val=6.0, max_val=60.0)
                if not ok: return False, err, {}
                sanitized_mb["width"] = mb_w
            if "length" in mb_dict:
                ok, err, mb_l = _parse_finite_float(mb_dict["length"], "masterBedroom.length", min_val=6.0, max_val=60.0)
                if not ok: return False, err, {}
                sanitized_mb["length"] = mb_l

        sanitized_kit = {}
        if "kitchen" in reqs and isinstance(reqs["kitchen"], dict):
            kit_dict = reqs["kitchen"]
            if "width" in kit_dict:
                ok, err, kit_w = _parse_finite_float(kit_dict["width"], "kitchen.width", min_val=4.0, max_val=40.0)
                if not ok: return False, err, {}
                sanitized_kit["width"] = kit_w
            if "length" in kit_dict:
                ok, err, kit_l = _parse_finite_float(kit_dict["length"], "kitchen.length", min_val=4.0, max_val=40.0)
                if not ok: return False, err, {}
                sanitized_kit["length"] = kit_l

        sanitized = {
            "plot": {
                "widthInches": w_in,
                "lengthInches": l_in,
                "widthFt": round(w_in / 12.0, 2),
                "lengthFt": round(l_in / 12.0, 2),
                "widthMeters": round(w_in * 0.0254, 3),
                "lengthMeters": round(l_in * 0.0254, 3),
                "widthMm": round(w_in * 25.4, 1),
                "lengthMm": round(l_in * 25.4, 1),
                "facing": facing_matched,
                "unitSystem": unit_system,
                "setbacks": setback_dict
            },
            "requirements": {
                "bedrooms": bhk,
                "masterBedroom": sanitized_mb,
                "kitchen": sanitized_kit,
                "pooja": bool(reqs.get("pooja", False)),
                "parking": bool(reqs.get("parking", False)),
                "attachedToilet": bool(reqs.get("attachedToilet", False)),
                "balcony": bool(reqs.get("balcony", False)),
                "study": bool(reqs.get("study", False))
            }
        }

        return True, None, sanitized

    def evaluate_feasibility(self, user_request: Dict[str, Any]) -> Dict[str, Any]:
        """
        Evaluates spatial feasibility and returns non-destructive, strictly validated advice.
        Guarantees:
        - Never silently discards or alters user request.
        - Fails closed on invalid or non-finite inputs.
        - Alternative recommendations compute real neural model predictions without hardcoded percentages.
        - Discloses that setbacks and decision margin scores are heuristics, not certified engineering codes.
        """
        start_time = time.perf_counter()

        # 1. Input Validation (Fail-Closed)
        is_valid, err_msg, sanitized = self.validate_inputs(user_request)
        if not is_valid:
            return {
                "status": "INPUT_ERROR",
                "is_feasible": False,
                "confidence_score": 0.0,
                "decision_margin_score": 0.0,
                "is_calibrated": False,
                "confidence_note": "Uncalibrated decision margin heuristic reflecting distance from 0.5 decision boundary.",
                "feasibility_probability": 0.0,
                "original_request": user_request,
                "error": err_msg,
                "disclaimer": DISCLAIMER_TEXT,
                "latency_ms": {
                    "model_inference": 0.0,
                    "total_advisor_overhead": round((time.perf_counter() - start_time) * 1000.0, 3)
                }
            }

        plot = sanitized["plot"]
        reqs = sanitized["requirements"]
        w_in = plot["widthInches"]
        l_in = plot["lengthInches"]
        plot_area_sqft = (w_in * l_in) / 144.0
        requested_bhk = reqs["bedrooms"]

        # 2. Buildable Envelope Calculation with Explicit Setback Disclosure
        sb = plot["setbacks"]
        buildable_w = max(0.0, w_in - (sb["left"] + sb["right"]))
        buildable_l = max(0.0, l_in - (sb["front"] + sb["rear"]))
        buildable_area_sqft = (buildable_w * buildable_l) / 144.0

        if not math.isfinite(buildable_area_sqft):
            return {
                "status": "CALCULATION_ERROR",
                "is_feasible": False,
                "error": "Non-finite buildable envelope area encountered.",
                "disclaimer": DISCLAIMER_TEXT
            }

        # 3. Checkpoint Model Inference
        model_lat_ms = 0.0
        if not self.is_model_ready or self.model is None:
            # Fallback heuristic mode if model unavailable
            feasibility_prob = 0.5
            is_feasible = bool(buildable_area_sqft >= (requested_bhk * 250.0 + 300.0))
            decision_margin = 0.20
            slot_advice = []
            model_status = f"FALLBACK_MODE (Checkpoint error: {self.init_error})"
        else:
            t0 = time.perf_counter()
            features = extract_input_features(sanitized)
            if torch is not None and isinstance(self.model, SpatialLayoutMLP):
                with torch.no_grad():
                    preds = self.model(features.unsqueeze(0))
            else:
                preds = self.model(features)
            t1 = time.perf_counter()
            model_lat_ms = (t1 - t0) * 1000.0

            raw_feas = preds["pred_feasibility_logits"][0]
            if hasattr(raw_feas, "item"):
                feasibility_logit = raw_feas.item()
            elif hasattr(raw_feas, "__len__"):
                feasibility_logit = float(raw_feas[0])
            else:
                feasibility_logit = float(raw_feas)

            feasibility_prob = 1.0 / (1.0 + math.exp(-feasibility_logit))
            is_feasible = bool(feasibility_prob >= 0.5)

            # Decision boundary distance scaled to [0, 1]
            decision_margin = round(abs(feasibility_prob - 0.5) * 2.0, 4)

            # Extract room-slot probabilities and estimated sizing
            pred_boxes = preds["pred_boxes"][0]
            if hasattr(pred_boxes, "detach"):
                pred_boxes = pred_boxes.detach().cpu().numpy()
            elif hasattr(pred_boxes, "numpy"):
                pred_boxes = pred_boxes.numpy()

            pred_mask_logits = preds["pred_mask_logits"][0]
            if hasattr(pred_mask_logits, "detach"):
                pred_mask_logits = pred_mask_logits.detach().cpu().numpy()
            elif hasattr(pred_mask_logits, "numpy"):
                pred_mask_logits = pred_mask_logits.numpy()

            pred_mask_probs = 1.0 / (1.0 + np.exp(-pred_mask_logits))

            slot_advice = []
            for s_idx, slot_name in enumerate(ROOM_SLOTS):
                p_active = float(pred_mask_probs[s_idx])
                w_ft = round(float((pred_boxes[s_idx, 2] * w_in) / 12.0), 1)
                l_ft = round(float((pred_boxes[s_idx, 3] * l_in) / 12.0), 1)
                slot_advice.append({
                    "slot": slot_name,
                    "active_probability": round(p_active, 3),
                    "recommended_active": bool(p_active >= 0.5),
                    "estimated_dimensions_ft": f"{w_ft}' x {l_ft}'",
                    "estimated_area_sqft": round(float(w_ft * l_ft), 1)
                })
            model_status = "MODEL_EVALUATED"

        # 4. Deterministic Envelope Safeguard Check
        min_area_needed = (requested_bhk * 200.0) + 300.0 # bedrooms + living + kitchen + bath
        envelope_capacity_warning = None
        if buildable_area_sqft < min_area_needed:
            envelope_capacity_warning = (
                f"Buildable envelope ({buildable_area_sqft:.0f} sq ft after setbacks) is below simplified rule-of-thumb "
                f"guideline ({min_area_needed:.0f} sq ft) for a {requested_bhk}BHK home."
            )
            if is_feasible and feasibility_prob < 0.75:
                # Soft downgrade to borderline warning
                is_feasible = False
                feasibility_prob = min(feasibility_prob, 0.45)

        # 5. Dynamic Neural Evaluation of Proposed Alternatives (No Hardcoded Strings)
        status = "FEASIBLE" if is_feasible else "CONSTRAINED_WARNING"
        warnings = []
        proposed_alternatives = []

        if not is_feasible or envelope_capacity_warning:
            if envelope_capacity_warning:
                warnings.append(envelope_capacity_warning)
            warnings.append(
                f"Requested {requested_bhk}BHK on a {plot['widthFt']}' x {plot['lengthFt']}' site ({plot_area_sqft:.0f} sq ft) "
                f"is prone to spatial overlap or sub-minimum room sizes."
            )

            # Calculate safe candidate BHKs
            max_safe_bhk = max(1, min(4, int(max(1.0, (buildable_area_sqft - 300.0) / 220.0))))
            candidate_bhks = []
            if max_safe_bhk < requested_bhk:
                candidate_bhks.append((max_safe_bhk, "Standard room dimensions & comfortable circulation"))
                if max_safe_bhk + 1 < requested_bhk:
                    candidate_bhks.append((max_safe_bhk + 1, "Compact room dimensions"))

            for alt_bhk, alt_desc in candidate_bhks:
                # Construct valid alternative request to run through model
                alt_req = copy.deepcopy(sanitized)
                alt_req["requirements"]["bedrooms"] = alt_bhk

                alt_prob: Optional[float] = None
                method = "QUALITATIVE_ARCHITECTURAL_HEURISTIC"
                qualitative_label = "HIGH_LIKELIHOOD" if alt_bhk <= 2 else "MODERATE_LIKELIHOOD"

                if self.is_model_ready and self.model is not None:
                    try:
                        alt_features = extract_input_features(alt_req)
                        if torch is not None and isinstance(self.model, SpatialLayoutMLP):
                            with torch.no_grad():
                                alt_preds = self.model(alt_features.unsqueeze(0))
                        else:
                            alt_preds = self.model(alt_features)

                        raw_alt_feas = alt_preds["pred_feasibility_logits"][0]
                        if hasattr(raw_alt_feas, "item"):
                            alt_logit = raw_alt_feas.item()
                        elif hasattr(raw_alt_feas, "__len__"):
                            alt_logit = float(raw_alt_feas[0])
                        else:
                            alt_logit = float(raw_alt_feas)

                        alt_prob = round(1.0 / (1.0 + math.exp(-alt_logit)), 4)
                        method = "EXPERIMENTAL_MODEL_SCORE"
                        if alt_prob >= 0.80:
                            qualitative_label = "HIGH_LIKELIHOOD"
                        elif alt_prob >= 0.50:
                            qualitative_label = "MODERATE_LIKELIHOOD"
                        else:
                            qualitative_label = "MARGINAL_LIKELIHOOD"
                    except Exception:
                        alt_prob = None

                alt_entry = {
                    "recommendation": f"{alt_bhk}BHK Configuration",
                    "reason": f"Estimated to accommodate within {buildable_area_sqft:.0f} sq ft envelope ({alt_desc}); subject to detailed CAD solver clearance.",
                    "feasibility_assessment": qualitative_label,
                    "assessment_method": method
                }
                if alt_prob is not None:
                    alt_entry["computed_model_probability"] = alt_prob

                proposed_alternatives.append(alt_entry)
        else:
            warnings.append(
                f"Plot envelope ({buildable_area_sqft:.0f} sq ft) estimated to accommodate {requested_bhk}BHK; final geometric placement verified by CAD solver."
            )

        total_lat_ms = round((time.perf_counter() - start_time) * 1000.0, 3)

        return {
            "status": status,
            "is_feasible": is_feasible,
            "feasibility_probability": round(float(feasibility_prob), 4),
            "confidence_score": decision_margin, # Preserved for backwards API compatibility
            "decision_margin_score": decision_margin,
            "is_calibrated": False,
            "confidence_note": "Decision-margin heuristic reflecting distance from 0.5 decision threshold; not an empirically calibrated posterior probability.",
            "model_status": model_status,
            "original_request": sanitized,
            "envelope_metrics": {
                "plot_area_sqft": round(plot_area_sqft, 1),
                "buildable_area_sqft": round(buildable_area_sqft, 1),
                "buildable_dimensions_ft": f"{buildable_w/12:.1f}' x {buildable_l/12:.1f}'",
                "setback_metrics": {
                    "front_inches": round(sb["front"], 1),
                    "rear_inches": round(sb["rear"], 1),
                    "left_inches": round(sb["left"], 1),
                    "right_inches": round(sb["right"], 1),
                    "source": sb["source"],
                    "disclosure": "Generic illustrative setback assumption. Not a certified local building code or municipal zoning determination."
                }
            },
            "warnings": warnings,
            "proposed_alternatives": proposed_alternatives,
            "slot_advice": slot_advice,
            "disclaimer": DISCLAIMER_TEXT,
            "latency_ms": {
                "model_inference": round(model_lat_ms, 3),
                "total_advisor_overhead": total_lat_ms
            }
        }


